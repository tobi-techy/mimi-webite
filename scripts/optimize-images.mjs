/**
 * Image pipeline (run with `npm run optimize:images` after adding or changing a source image).
 *
 * Sources stay untouched and are never shipped:
 *   src/features/marketing/assets/photos/*.jpg  -> public/media/photos/<name>-<w>.avif|webp + <name>-og.jpg
 *   assets-src/stickers/*.webp|png               -> public/stickers/<name>.webp (max 500px wide = 2x render size)
 *   assets-src/media/hero-home-poster.jpg        -> public/media/hero-home-poster.webp (1280px)
 * and writes src/features/marketing/assets/photos/photos.generated.ts (sizes + blur placeholders).
 *
 * Quality is set high on purpose (owner rule: no visible softening, banding or artefacts):
 * AVIF q62, WebP q84 for photos; WebP q85 with lossless-quality alpha for stickers.
 * The savings come from right-sizing and modern formats, not from crushing quality.
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const PHOTO_SRC = path.join(root, "src/features/marketing/assets/photos");
const PHOTO_OUT = path.join(root, "public/media/photos");
const STICKER_SRC = path.join(root, "assets-src/stickers");
const STICKER_OUT = path.join(root, "public/stickers");
const MEDIA_SRC = path.join(root, "assets-src/media");
const MEDIA_OUT = path.join(root, "public/media");

/** Must match images.deviceSizes in next.config.ts. */
export const PHOTO_WIDTHS = [480, 768, 1024, 1376, 1600, 1920, 2560];
const STICKER_MAX_W = 500;

async function photos() {
  await mkdir(PHOTO_OUT, { recursive: true });
  const files = (await readdir(PHOTO_SRC)).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort();
  const manifest = {};
  for (const file of files) {
    const name = file.replace(/\.[^.]+$/, "");
    const src = sharp(path.join(PHOTO_SRC, file));
    const { width, height } = await src.metadata();
    const widths = [...new Set(PHOTO_WIDTHS.map((w) => Math.min(w, width)))];
    for (const w of widths) {
      const base = sharp(path.join(PHOTO_SRC, file)).resize({ width: w, withoutEnlargement: true });
      await base
        .clone()
        .avif({ quality: 62, effort: 6, chromaSubsampling: "4:4:4" })
        .toFile(path.join(PHOTO_OUT, `${name}-${w}.avif`));
      await base
        .clone()
        .webp({ quality: 84, effort: 6, smartSubsample: true })
        .toFile(path.join(PHOTO_OUT, `${name}-${w}.webp`));
    }
    await sharp(path.join(PHOTO_SRC, file))
      .resize({ width: 1200, withoutEnlargement: true })
      .jpeg({ quality: 85, mozjpeg: true })
      .toFile(path.join(PHOTO_OUT, `${name}-og.jpg`));
    const blur = await sharp(path.join(PHOTO_SRC, file))
      .resize({ width: 16 })
      .webp({ quality: 50 })
      .toBuffer();
    manifest[name] = {
      width,
      height,
      widths,
      og: `/media/photos/${name}-og.jpg`,
      blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
    };
  }
  const ts = `/* Generated by scripts/optimize-images.mjs. Do not edit by hand. */
export const photoManifest = ${JSON.stringify(manifest, null, 2)} as const;

export type PhotoKey = keyof typeof photoManifest;
`;
  await writeFile(path.join(PHOTO_SRC, "photos.generated.ts"), ts);
  console.log(`photos: ${files.length} sources`);
}

async function stickers() {
  const files = (await readdir(STICKER_SRC)).filter((f) => /\.(webp|png)$/i.test(f)).sort();
  for (const file of files) {
    const name = file.replace(/\.[^.]+$/, "");
    await sharp(path.join(STICKER_SRC, file))
      .resize({ width: STICKER_MAX_W, withoutEnlargement: true, kernel: "lanczos3" })
      .webp({ quality: 85, alphaQuality: 100, effort: 6, smartSubsample: true })
      .toFile(path.join(STICKER_OUT, `${name}.webp`));
  }
  console.log(`stickers: ${files.length}`);
}

async function poster() {
  const src = path.join(MEDIA_SRC, "hero-home-poster.jpg");
  await sharp(src)
    .resize({ width: 1280, withoutEnlargement: true })
    .webp({ quality: 80, effort: 6 })
    .toFile(path.join(MEDIA_OUT, "hero-home-poster.webp"));
  console.log("poster: done");
}

await photos();
await stickers();
await poster();
