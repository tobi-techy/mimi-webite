           f'export const lookExpressions: readonly HelperExpression[] = {json.dumps(LOOK_EXPRS)};',
           f'export const helperLook: Record<HelperKey, readonly [number, number]> = {json.dumps(looks)};',
           '/** v6 family colours (tiles and stickers only; product UI is one colour). */',
           f'export const helperColour: Record<HelperKey, string> = {json.dumps(fam)};',
           f'export const helperColourName: Record<HelperKey, string> = {json.dumps(COLOUR)};',
           f'export const helperCue: Record<HelperKey, string> = {json.dumps(CUE)};',
