os.makedirs(COMP, exist_ok=True); os.makedirs(PUB, exist_ok=True)
T_FG, T_CUT, T_EYE = '#FG#', '#CUT#', '#EYE#'
LOOK_EXPRS = ['idle', 'determined', 'surprised', 'sleepy']

def themeable(s):
    """literal FG/CUT/EYE colours -> nothing (CSS classes .f .c .h .e .es paint them)"""
    s = s.replace(f' fill="{T_FG}"', '').replace(f' fill="{T_CUT}"', '').replace(f' fill="{T_EYE}"', '')
    s = s.replace(f' stroke="{T_CUT}"', '').replace(f' stroke="{T_EYE}"', '')
    assert '#FG#' not in s and '#CUT#' not in s and '#EYE#' not in s, 'unreplaced colour token'
    return s

def rig(k):
    pid = '__ID__'
    full = build(k, fg=T_FG, cut=T_CUT, eye=T_EYE, prefix=pid, standalone=False)
    eyes = eyes_svg(pid, 'idle', {}).replace('{FG}', T_FG).replace('{CUT}', T_CUT).replace('{EYE}', T_EYE)
    assert eyes in full
    full = full.replace(eyes, '__EXPR__')
    lx, ly = H[k]['look']
    look = f'<g class="rig-look" transform="translate({lx} {ly})">'
    assert look in full
    full = full.replace(look, '<g class="rig-look" transform="__LOOK__">')
    # status marks start hidden; CSS shows them per state (dot = working, ring = waiting on owner)
    full = re.sub(r'(class="(?:c )?rig-halo"[^>]*?) opacity="[\d.]+"', r'\1', full)
    full = re.sub(r'(class="rig-dot"[^>]*?) opacity="[\d.]+"', r'\1', full)
    full = re.sub(r'(class="rig-ring"[^>]*?) opacity="[\d.]+"', r'\1', full)
    return themeable(full)

def expr_layers():
    pid = '__ID__'
    allx = eyes_svg(pid, 'idle', {}).replace('{FG}', T_FG).replace('{CUT}', T_CUT).replace('{EYE}', T_EYE)
    parts = allx.split(f'<g id="{pid}-expr-')[1:]
    out = {}
    for p in parts:
        name = p.split('"', 1)[0]
        layer = f'<g id="{pid}-expr-' + p
        layer = layer.replace(' opacity="0"', '', 1)
        out[name] = themeable(layer)
    assert list(out) == EXPRS, list(out)
    return out

def mimi_mark():
    s = mimi(fg=T_FG, cut=T_CUT, eye=T_EYE, scale=0.82)
    # mimi() writes fills inline without classes: map them onto the same classes
    s = s.replace(f'fill="{T_FG}"', 'class="f"').replace(f'fill="{T_CUT}" stroke="{T_CUT}"', 'class="h"').replace(f'fill="{T_EYE}"', 'class="e"')
    s = s.replace(f'fill="{T_CUT}"', 'class="c"')
    assert '#' not in re.sub(r'url\(#[^)]*\)', '', s.replace('#ee6018', '')), s[:200]
    return s

def css():
    L = ['/* Mimi helpers v6 rig: GENERATED by mimi-helpers/v6/export_web_v6.py from helpers_v6.py + motion_v6.py.',
         '   Do not edit by hand; edit the Python source and re-run the export. */',
         '.mimi-helper { --h-fg: currentColor; --h-cut: var(--h-surface, var(--bg, #101010)); --h-eye: var(--h-cut);',
         '  display: block; overflow: visible; flex: none; }',
         '.mimi-helper .f { fill: var(--h-fg); }',
         '.mimi-helper .c, .mimi-helper .h { fill: var(--h-cut); }',
         '.mimi-helper .h { stroke: var(--h-cut); }',
         '.mimi-helper .e { fill: var(--h-eye); }',
         '.mimi-helper .es { fill: none; stroke: var(--h-eye); }',
         '.mimi-helper .rig-root, .mimi-helper .rig-acc, .mimi-helper .rig-part, .mimi-helper .rig-face, .mimi-helper .rig-prop,',
         '.mimi-helper .rig-lid, .mimi-helper .rig-dot, .mimi-helper .rig-ring { transform-box: view-box; }',
         f'.mimi-helper .rig-root {{ transform-origin: {PIVOT[0]}px {PIVOT[1]}px; }}',
         f'.mimi-helper .rig-face {{ transform-origin: {FACE_O[0]}px {FACE_O[1]}px; }}',
         '/* status: orange dot = working, orange ring = waiting on the owner; nothing else is orange */',
         '.mimi-helper .rig-dot, .mimi-helper .rig-ring, .mimi-helper .rig-halo { opacity: 0; transition: opacity 180ms cubic-bezier(0.4, 0, 0.2, 1); }',
         '.mimi-helper[data-state="working"] .rig-dot, .mimi-helper[data-state="working"] .rig-halo,',
         '.mimi-helper[data-state="waiting"] .rig-ring, .mimi-helper[data-state="waiting"] .rig-halo { opacity: 1; }',
         '.mimi-helper[data-marks="off"] .rig-status { display: none; }']
    for k in ORDER:
        h = H[k]
        L.append(f'.mimi-helper[data-helper="{k}"] .rig-acc {{ transform-origin: {f(h["acc_o"][0])}px {f(h["acc_o"][1])}px; }}')
        L.append(f'.mimi-helper[data-helper="{k}"] .rig-part {{ transform-origin: {f(h["part_o"][0])}px {f(h["part_o"][1])}px; }}')
        po = h.get('prop_o', PIVOT)
        L.append(f'.mimi-helper[data-helper="{k}"] .rig-prop {{ transform-origin: {f(po[0])}px {f(po[1])}px; }}')
        if h.get('prop_rest_o') == 0:
            L.append(f'.mimi-helper[data-helper="{k}"] .rig-prop {{ opacity: 0; }}')
    # eye lids sit on the eye centre (blink travel is in rig units)
    for side, s in (('l', -1), ('r', 1)):
        L.append(f'.mimi-helper .rig-eye-{side} .rig-lid {{ transform-origin: {f(120 + s*EYE_DX)}px {EYE_Y}px; }}')
    L.append('')
    L.append('/* ---- motion (motion_v6.py tracks; same data as motion.html and lineup.mp4) ---- */')
    mc = M.css(ORDER)
    mc = mc.replace('--ease-', '--hx-ease-').replace('--dur-', '--hx-dur-')
    mc = mc.replace(':root {', '.mimi-helper {', 1)
    L.append(mc)
    L.append('')
    still = ('.mimi-helper.is-still *, .mimi-helper.is-settled[data-state="done"] * { animation: none !important; }')
    L += ['/* still: tiny inline faces and a done face that was already done on mount (no pop on page load) */', still,
          '/* reduced motion: no loops; each state is a still pose (eyes + one orange mark carry it) */',
          '@media (prefers-reduced-motion: reduce) {',
          '  .mimi-helper * { animation: none !important; transition: none !important; }',
          '}',
          '.mimi-helper.is-still[data-state="working"] .rig-face { transform: translate(-4px, 3px); }',
          '.mimi-helper.is-still[data-state="waiting"] .rig-face { transform: translate(0, -8px); }',
          '@media (prefers-reduced-motion: reduce) {',
          '  .mimi-helper[data-state="working"] .rig-face { transform: translate(-4px, 3px); }',
          '  .mimi-helper[data-state="waiting"] .rig-face { transform: translate(0, -8px); }',
          '}']
    return '\n'.join(L) + '\n'

